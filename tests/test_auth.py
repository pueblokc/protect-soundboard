"""The siren (and every other control) must not be reachable without the token."""
import app as app_module
import pytest
from conftest import TOKEN

CONTROL = [
    ("/api/siren", {"action": "activate", "duration": 10}),
    ("/api/siren", {"action": "stop"}),
    ("/api/volume", {"target": "siren", "volume": 100, "allow_loud": True}),
    ("/api/speak", {"text": "hello"}),
    ("/api/play-sound", {"file": "Air Horn.mp3"}),
    ("/api/presets", {"tts": []}),
]


@pytest.mark.parametrize("path,body", CONTROL)
def test_control_endpoints_reject_missing_token(client, fake, path, body):
    r = client.jpost(path, body, token=None)
    assert r.status_code == 401
    assert fake.engine.calls == [] and fake.tb.streams == []


@pytest.mark.parametrize("path,body", CONTROL)
def test_control_endpoints_reject_wrong_token(client, fake, path, body):
    r = client.jpost(path, body, token="nope")
    assert r.status_code == 401
    assert fake.engine.calls == []


@pytest.mark.parametrize("path", ["/api/status", "/api/presets", "/api/sounds"])
def test_reads_require_token(client, path):
    assert client.jget(path, token=None).status_code == 401
    assert client.jget(path).status_code == 200


def test_bearer_header_accepted(client, fake):
    r = client.post("/api/siren", json={"action": "stop"}, headers={"Authorization": f"Bearer {TOKEN}"})
    assert r.status_code == 200
    assert fake.engine.calls == [("siren_off",)]


def test_cross_site_text_plain_post_is_rejected(client, fake):
    # a cross-site <form>/fetch can only send "simple" content types; old code used force=True
    r = client.post("/api/siren", data='{"action":"activate"}', content_type="text/plain",
                    headers={"X-Soundboard-Token": TOKEN})
    assert r.status_code == 415
    r = client.post("/api/siren", data='{"action":"activate"}', content_type="text/plain")
    assert r.status_code == 401
    assert fake.engine.calls == []


def test_index_is_public_and_has_security_headers(client):
    r = client.get("/")
    assert r.status_code == 200
    assert r.headers["X-Frame-Options"] == "DENY"
    assert r.headers["X-Content-Type-Options"] == "nosniff"


def test_token_file_autogenerated_private(monkeypatch, tmp_path):
    monkeypatch.delenv("SOUNDBOARD_TOKEN", raising=False)
    f = tmp_path / ".soundboard_token"
    monkeypatch.setattr(app_module, "TOKEN_FILE", f)
    tok = app_module._load_or_create_token()
    assert len(tok) >= 24
    assert f.read_text().strip() == tok
    assert (f.stat().st_mode & 0o777) == 0o600
    assert app_module._load_or_create_token() == tok  # stable across restarts


def test_env_token_wins(monkeypatch, tmp_path):
    monkeypatch.setenv("SOUNDBOARD_TOKEN", "from-env")
    monkeypatch.setattr(app_module, "TOKEN_FILE", tmp_path / "t")
    assert app_module._load_or_create_token() == "from-env"
    assert not (tmp_path / "t").exists()


def test_auth_off_switch(monkeypatch):
    monkeypatch.setenv("SOUNDBOARD_AUTH", "off")
    assert app_module._auth_disabled()
    monkeypatch.setenv("SOUNDBOARD_AUTH", "")
    assert not app_module._auth_disabled()
